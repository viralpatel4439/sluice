// Embeds proto/sluice.proto into src/remote/proto-text.ts so the package needs no file lookups at runtime.
import { readFileSync, writeFileSync } from "node:fs";
const text = readFileSync(new URL("../proto/sluice.proto", import.meta.url), "utf8");
writeFileSync(
  new URL("../src/remote/proto-text.ts", import.meta.url),
  `// Generated by scripts/gen-proto.mjs from proto/sluice.proto. Do not edit.\nexport const PROTO_TEXT = ${JSON.stringify(text)};\n`,
);
